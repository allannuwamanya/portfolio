/**
 * Regenerates src/components/shared/tech-icon-paths.ts from the official Simple Icons data.
 *
 * Brand glyphs are large path payloads; hand-copying them is how logos end up subtly
 * mangled. This script is the single source of truth for that data.
 *
 *   node scripts/fetch-tech-icons.mjs
 *
 * Simple Icons is CC0-1.0 licensed.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CDN = "https://cdn.jsdelivr.net/npm/simple-icons@latest";
const toSlug = (title) => title.toLowerCase().replace(/[^a-z0-9]+/g, "-");

const manifest = JSON.parse(
  await readFile(join(ROOT, "src/data/tech-icon-manifest.json"), "utf8"),
);

const catalogue = await fetch(`${CDN}/_data/simple-icons.json`).then((r) => r.json());
const bySlug = new Map(catalogue.map((icon) => [toSlug(icon.title), icon]));

/** @type {Record<string, { d: string; hex: string }>} */
const paths = {};
const problems = [];

for (const [id, slug] of Object.entries(manifest.icons)) {
  if (!slug) continue;

  const brand = bySlug.get(slug);
  if (!brand) {
    problems.push(`${id} -> "${slug}" is not in Simple Icons (would fall back to a neutral glyph)`);
    continue;
  }

  const file = manifest.svgSlugs?.[id] ?? slug;
  const svg = await fetch(`${CDN}/icons/${file}.svg`).then((r) => r.text());
  const d = svg.match(/<path d="([^"]+)"/)?.[1];
  if (!d) {
    problems.push(`${id} -> ${file}.svg (fetched, but no <path> found)`);
    continue;
  }

  paths[id] = { d, hex: `#${brand.hex}` };
}

const body = `// AUTO-GENERATED by scripts/fetch-tech-icons.mjs — do not edit by hand.
// Source: Simple Icons (https://simpleicons.org), CC0-1.0.

export interface TechIconPath {
  /** SVG path data, drawn on a 24x24 viewBox. */
  d: string;
  /** Brand colour as a hex string. */
  hex: string;
}

export const TECH_ICON_PATHS: Record<string, TechIconPath> = ${JSON.stringify(paths, null, 2)};
`;

await writeFile(join(ROOT, "src/components/shared/tech-icon-paths.ts"), body);

console.log(`Wrote ${Object.keys(paths).length} brand icons.`);
if (problems.length) {
  console.log(`\n${problems.length} unresolved:`);
  for (const p of problems) console.log(`  - ${p}`);
}